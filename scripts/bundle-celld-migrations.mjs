#!/usr/bin/env node
// Bundles migrations/ into the durable-sqlite migrator bundle the
// RegistryDatabase Durable Object applies at boot on celld.
//
// migrations/ stays the single source of truth for schema: this script only
// reads `migrations/meta/_journal.json` and the `.sql` files it references,
// and writes `src/db/migrations/celld-bundle.ts` with the SQL inlined.
// (The SQL text is embedded rather than imported `?raw` because wrangler's
// bundler has no loader for `.sql` files — `?raw` builds fine in the vitest
// pool but fails `wrangler deploy`.)
//
// Regenerate after every `pnpm db:generate` (which runs this automatically):
//
//   pnpm celld:db:bundle

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journalPath = join(root, "migrations", "meta", "_journal.json");
const outPath = join(root, "src", "db", "migrations", "celld-bundle.ts");

const journal = JSON.parse(readFileSync(journalPath, "utf8"));
const entries = journal.entries;
if (!Array.isArray(entries) || entries.length === 0) {
  throw new Error("celld bundle: migrations/meta/_journal.json has no entries");
}

function toTemplateLiteral(sql) {
  return sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const migrationEntries = [];
for (const entry of entries) {
  if (entry.idx !== migrationEntries.length) {
    throw new Error(
      `celld bundle: journal idx gap at ${migrationEntries.length} (expected ${migrationEntries.length}, found ${entry.idx}, tag ${entry.tag})`,
    );
  }
  const sqlFile = join(root, "migrations", `${entry.tag}.sql`);
  if (!existsSync(sqlFile)) {
    throw new Error(`celld bundle: journal references missing file ${entry.tag}.sql`);
  }
  const key = `m${String(entry.idx).padStart(4, "0")}`;
  const sql = readFileSync(sqlFile, "utf8");
  migrationEntries.push(`  ${key}: \`${toTemplateLiteral(sql)}\`,`);
}

const journalLines = JSON.stringify(journal, null, 2).split("\n");
const journalJson =
  journalLines[0] +
  "\n" +
  journalLines
    .slice(1)
    .map((line) => (line.trim() === "" ? "" : `  ${line}`))
    .join("\n");

const body = `/**
 * AUTO-GENERATED by scripts/bundle-celld-migrations.mjs — do not edit by hand.
 *
 * The durable-sqlite migration bundle for the celld RegistryDatabase Durable
 * Object. Regenerate after \`pnpm db:generate\` (which chains this script):
 *
 *   pnpm celld:db:bundle
 *
 * \`migrations/\` remains the single source of truth for schema; the SQL text
 * below is generated verbatim from those files.
 */
export const celldJournal = ${journalJson};

export const celldMigrations: Record<string, string> = {
${migrationEntries.join("\n")}
};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body);
console.log(`celld bundle: ${entries.length} migrations -> ${outPath}`);
